const memory=new WeakMap();
const attributes=new WeakMap();

const loyaltySentences=[
  [/^Баллы начисляются с оплаченных сумм: (\d+(?:[.,]\d+)?) балл(?:а|ов)? за каждые 100 ₸\./, (_,rate)=>`Төленген әр 100 ₸ үшін ${rate} ұпай беріледі.`],
  [/Скидка дня рождения действует (\d+) дн\. до и после даты\./, (_,days)=>`Туған күн жеңілдігі туған күнге дейін және одан кейін ${days} күн бойы қолданылады.`],
];
