function translate(text){
  if(!/[А-Яа-яЁё]/.test(text))return text;
  const leading=(text.match(/^\s*/)||[''])[0];
  const trailing=(text.match(/\s*$/)||[''])[0];
  let result=text.trim();
  if(dictionary[result])return leading+dictionary[result]+trailing;
  for(const [pattern,render] of dynamic){
    if(pattern.test(result))return leading+result.replace(pattern,render)+trailing;
  }
  for(const [pattern,render] of embeddedPhrases)result=result.replace(pattern,render);
  result=result.replace(labels,match=>dictionary[match]??match);
  return leading+result+trailing;
}

function textNode(n){
  if(!n||!n.parentElement)return;
  const p=n.parentElement;
  if(/^(SCRIPT|STYLE|NOSCRIPT|TEXTAREA|CODE|PRE)$/i.test(p.tagName))return;
  if(p.closest?.('[data-shipa-no-translate]'))return;
  const value=n.nodeValue||'';
  let state=memory.get(n);
  if(!state||value!==state.out)state={source:value,out:value};
  const output=lang==='KZ'?translate(state.source):state.source;
  memory.set(n,{source:state.source,out:output});
  if(value!==output)n.nodeValue=output;
}

function elementAttributes(el){
  if(!el||!el.getAttribute)return;
  if(el.closest?.('[data-shipa-no-translate]'))return;
  const attrs=['placeholder','aria-label','title','alt'];
  let record=attributes.get(el)||{};
  for(const name of attrs){
    if(!el.hasAttribute(name))continue;
    const value=el.getAttribute(name);
    let state=record[name];
    if(!state||value!==state.out)state={source:value,out:value};
    const output=lang==='KZ'?translate(state.source):state.source;
    record[name]={source:state.source,out:output};
    if(value!==output)el.setAttribute(name,output);
  }
  attributes.set(el,record);
}

function visit(root){
  if(!root)return;
  if(root.nodeType===3){textNode(root);return;}
  if(root.nodeType!==1)return;
  if(/^(SCRIPT|STYLE|NOSCRIPT|TEXTAREA|CODE|PRE)$/i.test(root.tagName))return;
  elementAttributes(root);
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  while(walker.nextNode())textNode(walker.currentNode);
  if(root.querySelectorAll){
    root.querySelectorAll('[placeholder],[aria-label],[title],[alt]')
      .forEach(elementAttributes);
  }
}

function updateButtons(){
  document.querySelectorAll('[data-shipa-lang]').forEach(b=>{
    const active=b.getAttribute('data-shipa-lang')===lang;
    b.style.background=active?'#C15C22':'transparent';
    b.style.color=active?'#fff':'#0A2F4F';
    b.setAttribute('aria-pressed',active?'true':'false');
  });
}

function apply(next){
  if(next!=='RU'&&next!=='KZ')return;
  lang=next;
  document.documentElement.lang=lang==='KZ'?'kk':'ru';
  try{localStorage.setItem('shipa-lang',lang);}catch(e){}
  visit(document.body);
  updateButtons();
  window.dispatchEvent(new Event('shipa:localechange'));
}

document.addEventListener('click',e=>{
  const b=e.target.closest&&e.target.closest('button');
  if(!b)return;
  const choice=b.getAttribute('data-shipa-lang')||(b.textContent||'').trim();
  if(choice==='RU'||choice==='KZ'){
    setTimeout(()=>apply(choice),0);
  }
},true);

function start(){
  apply(lang);
  const observer=new MutationObserver(records=>{
    let refresh=false;
    for(const m of records){
      if(m.type==='characterData')textNode(m.target);
      else if(m.type==='attributes')elementAttributes(m.target);
      else if(m.type==='childList'){
        m.addedNodes.forEach(visit);
        refresh=true;
      }
    }
    if(refresh)updateButtons();
  });
  observer.observe(document.body,{
    subtree:true,childList:true,characterData:true,
    attributes:true,
    attributeFilter:['placeholder','title','aria-label','alt']
  });
}

window.ShipaLocale={set:apply,get:()=>lang,text:value=>lang==='KZ'?translate(value):value};

if(document.readyState==='loading'){
  document.addEventListener('DOMContentLoaded',start,{once:true});
}else start();

